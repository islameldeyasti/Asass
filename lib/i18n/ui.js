/** @param {keyof typeof ui} key @param {'en'|'ar'} locale */
export function t(key, locale = 'en') {
  const entry = ui[key];
  if (!entry) return key;
  return locale === 'ar' ? entry.ar : entry.en;
}

/** @param {keyof typeof navLabels} key @param {'en'|'ar'} locale */
export function tNav(key, locale = 'en') {
  const entry = navLabels[key];
  if (!entry) return key;
  return locale === 'ar' ? entry.ar : entry.en;
}

export function isAr(locale) {
  return locale === 'ar';
}
